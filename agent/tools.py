TZ_ALIASES = {
    "ist": "Asia/Kolkata", "india": "Asia/Kolkata", "pst": "America/Los_Angeles", "pdt": "America/Los_Angeles",
    "pt": "America/Los_Angeles", "est": "America/New_York", "edt": "America/New_York", "et": "America/New_York",
    "cst": "America/Chicago", "cdt": "America/Chicago", "mst": "America/Denver", "gmt": "Europe/London",
    "bst": "Europe/London", "uk": "Europe/London", "london": "Europe/London", "utc": "UTC", "cet": "Europe/Berlin",
    "cest": "Europe/Berlin", "sgt": "Asia/Singapore", "singapore": "Asia/Singapore", "gst": "Asia/Dubai",
    "dubai": "Asia/Dubai", "aest": "Australia/Sydney", "jst": "Asia/Tokyo",
}


def resolve_tz(name: str | None) -> Optional[str]:
    if not name:
        return None
    n = name.strip()
    if n.lower() in TZ_ALIASES:
        return TZ_ALIASES[n.lower()]
    try:
        ZoneInfo(n)
        return n
    except (ZoneInfoNotFoundError, ValueError):
        return None


# --------------------------------------------------------------------------- classify
class SlotReq(BaseModel):
    date: Optional[str] = None
    time: Optional[str] = None
    timezone: Optional[str] = None
    matches_proposed_index: Optional[int] = None


class Classification(BaseModel):
    category: str
    requested_slot: Optional[SlotReq] = None
    window: Optional[dict] = None
    prospect_timezone: Optional[str] = None
    ambiguity: Optional[str] = None
    questions: list[str] = Field(default_factory=list)
    referral: Optional[dict] = None
    reason: str = ""


def classify_reply(reply: str, times_proposed: list[str], last_agent_message: str, now: datetime) -> tuple[Classification, dict]:
    proposed = "\n".join(f"[{i}] {fmt_slot(s)}  ({s})" for i, s in enumerate(times_proposed[-3:])) or "(none yet)"
    local = now.astimezone(org_tz())
    return llm.get_llm().json("reply_classify", {
        "today": local.date().isoformat(), "weekday": local.strftime("%A"), "proposed": proposed,
        "last_agent_message": last_agent_message[:1500], "reply": reply[:3000]}, Classification)


def resolve_slot(c: Classification, state: dict) -> tuple[Optional[str], Optional[str]]:
    """Return (slot_iso, problem). Never infers the prospect's timezone from the organizer's."""
    rs = c.requested_slot
    recent = state.get("times_proposed", [])[-3:]
    if rs and rs.matches_proposed_index is not None and 0 <= rs.matches_proposed_index < len(recent):
        # They picked from our explicit IST-labelled list: the slot is exact.
        return recent[rs.matches_proposed_index], None
    if not rs or not rs.date or not rs.time:
        return None, c.ambiguity or "no exact date and time given"
    tzname = resolve_tz(rs.timezone) or state.get("prospect_tz")
    if not tzname:
        # Match against our proposed list (shown in IST) by date + time; otherwise ask.
        for s in recent:
            local = parse_iso(s)
            if local.date().isoformat() == rs.date and local.strftime("%H:%M") == rs.time[:5]:
                return s, None
        return None, f"timezone not stated for {rs.date} {rs.time}"
    try:
        dt = datetime.fromisoformat(f"{rs.date}T{rs.time[:5]}").replace(tzinfo=ZoneInfo(tzname))
    except ValueError:
        return None, f"could not parse date/time '{rs.date} {rs.time}'"
    return to_iso(dt), None


# --------------------------------------------------------------------------- calendar
def check_calendar(state: dict, now: datetime, window: dict | None = None, count: int = S.SLOTS_TO_PROPOSE,
                   sleep=_time.sleep) -> dict:
    exclude = set(state.get("rejected_slots", [])) | set(state.get("times_proposed", []))
    w = dict(window) if window else None
    if w and w.get("timezone"):
        w["timezone"] = resolve_tz(w["timezone"])
    last = None
    for attempt in range(1, S.MAX_FETCH_ATTEMPTS + 1):
        try:
            slots = get_calendar().free_slots(now, count, exclude, w)
            if not slots and w:
                slots = get_calendar().free_slots(now, count, exclude, None)
            return {"slots": slots, "checked_at": now.astimezone(timezone.utc).isoformat()}
        except Exception as e:  # transient calendar failure
            last = e
            if attempt < S.MAX_FETCH_ATTEMPTS:
                sleep(min(2 ** attempt, 4) * 0.01)
    raise CalendarError(f"calendar check failed after {S.MAX_FETCH_ATTEMPTS} attempts: {last}")


def approved_facts_text() -> str:
    return capabilities.as_prompt_text()


def _draft(purpose: str, thread: dict, reply: str) -> str:
    out, _ = llm.get_llm().json("reply_draft", {
        "name": thread["contact_name"], "first_name": thread["contact_name"].split()[0], "company": thread["company"],
        "purpose": purpose, "approved_facts": approved_facts_text(), "reply": reply[:2000]}, _Body)
    return out.body


class _Body(BaseModel):
    body: str


class InfoAnswer(BaseModel):
    body: str
    needs_handoff: bool = False
    handoff_reason: Optional[str] = None


def propose_times(slots: list[str], thread: dict, reply: str, prospect_tz: str | None, purpose_extra: str = "") -> dict:
    body = _draft("Offer these calendar-checked meeting slots for a 30-minute call and ask them to reply with the one "
                  "that works (or suggest another time with their timezone). " + purpose_extra, thread, reply)
    slot_lines = "\n".join(f"- {fmt_slot(s, prospect_tz)}" for s in slots)
    body = body.replace("[[SLOTS]]", slot_lines) if "[[SLOTS]]" in body else body.rstrip() + "\n\n" + slot_lines
    return {"kind": "propose_times", "body": body, "slots": slots}




def clarify(problem: str, thread: dict, reply: str) -> dict:
    body = _draft(f"Politely ask them to confirm an exact date, time and their timezone because: {problem}. "
                  "Do not propose times.", thread, reply)
    return {"kind": "clarify", "body": body.replace("[[SLOTS]]", "")}


def answer_info_request(c: Classification, thread: dict, reply: str) -> InfoAnswer:
    out, _ = llm.get_llm().json("info_answer", {
        "name": thread["contact_name"], "first_name": thread["contact_name"].split()[0], "company": thread["company"],
        "approved_facts": approved_facts_text(), "questions": "\n".join(f"- {q}" for q in c.questions) or "(see message)",
        "reply": reply[:2000]}, InfoAnswer)
    if re.search(r"(\$|₹|€|£)\s?\d|\bper (month|year|seat)\b|\bguarantee", out.body, re.I):
        return InfoAnswer(body="", needs_handoff=True, handoff_reason="draft contained pricing/guarantee language")
    return out


# --------------------------------------------------------------------------- booking
def build_ics(event_id: str, slot_iso: str, title: str, attendee: str, description: str, sequence: int = 0) -> str:
    s = parse_iso(slot_iso).astimezone(timezone.utc)
    e = s + timedelta(minutes=S.MEETING_MINUTES)
    f = lambda d: d.strftime("%Y%m%dT%H%M%SZ")
    stamp = f(datetime.now(timezone.utc))
    desc = description.replace("\n", "\\n").replace(",", "\\,")
    return "\r\n".join([
        "BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Sprinto Outbound Demo//EN", "METHOD:REQUEST", "BEGIN:VEVENT",
        f"UID:{event_id}@sprinto-demo", f"SEQUENCE:{sequence}", f"DTSTAMP:{stamp}", f"DTSTART:{f(s)}", f"DTEND:{f(e)}",
        f"SUMMARY:{title}", f"DESCRIPTION:{desc}",
        f"ORGANIZER;CN={S.ORGANIZER_NAME}:mailto:{S.DEMO_EMAIL}",
        f"ATTENDEE;CN=Demo attendee;RSVP=TRUE:mailto:{S.DEMO_EMAIL}",
        "STATUS:CONFIRMED", "END:VEVENT", "END:VCALENDAR", ""])


def book_meeting(state: dict, slot_iso: str, thread: dict, now: datetime) -> dict:
    """Fresh availability check, then create/update. Confirms only after the event exists."""
    from outreach.send import op_id
    s = parse_iso(slot_iso)
    if s <= now + timedelta(minutes=30) or s > now + timedelta(days=S.SCHEDULING_HORIZON_DAYS):
        return {"status": "INVALID", "reason": "slot is in the past or beyond the 30-day horizon", "slot": slot_iso}
    if not is_working_slot(s):
        return {"status": "INVALID", "reason": "outside organizer working hours (weekdays 09:00–18:00 IST)", "slot": slot_iso}
    if slot_iso in state.get("rejected_slots", []):
        return {"status": "INVALID", "reason": "slot was previously rejected", "slot": slot_iso}
    cal = get_calendar()
    existing = state.get("event_id")
    try:
        if not cal.is_free(s, ignore_event=existing):
            return {"status": "BUSY", "slot": slot_iso}
        title = f"Sprinto <> {thread['company']} — intro call (DEMO)"
        if existing:
            eid = cal.update_event(existing, s)
            kind = "RESCHEDULED"
        else:
            eid = cal.create_event(s, title, S.DEMO_EMAIL, thread["thread_id"], op_id(thread["thread_id"], "booking", slot_iso))
            kind = "CONFIRMED"
        ev = cal.get_event(eid)
        if not ev or parse_iso(ev["start_utc"]) != s.astimezone(timezone.utc):
            return {"status": "UNCERTAIN", "reason": "event not found after create/update", "slot": slot_iso, "event_id": eid}
        return {"status": "BOOKED", "kind": kind, "event_id": eid, "slot": slot_iso, "title": title}
    except CalendarError as e:
        return {"status": "UNCERTAIN", "reason": str(e), "slot": slot_iso}


# --------------------------------------------------------------------------- logging
def update_activity_log(domain: str, entries: list[dict], sleep=_time.sleep) -> bool:
    for attempt in range(1, S.MAX_FETCH_ATTEMPTS + 1):
        try:
            for e in entries:
                db.log_activity(domain, e["event"], e.get("detail"))
            return True
        except Exception:
            if attempt < S.MAX_FETCH_ATTEMPTS:
                sleep(0.05 * attempt)
    return False
